-- TEXT preserva a representação pública de datas e o JSON original de idempotência.
CREATE FUNCTION data_iso_valida(value TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
  IF value !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN RETURN false; END IF;
  RETURN to_char(value::date, 'YYYY-MM-DD') = value;
EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format THEN RETURN false;
END;
$$;

CREATE FUNCTION instante_utc_valido(value TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql STABLE STRICT AS $$
BEGIN
  IF right(value, 1) <> 'Z' THEN RETURN false; END IF;
  RETURN isfinite(value::timestamptz);
EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format THEN RETURN false;
END;
$$;

CREATE TABLE eventos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  nome TEXT NOT NULL CHECK (length(trim(nome)) > 0),
  data TEXT NOT NULL CHECK (data_iso_valida(data)),
  local TEXT NOT NULL CHECK (length(trim(local)) > 0)
);

CREATE TABLE portoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  evento_id BIGINT NOT NULL REFERENCES eventos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  nome TEXT NOT NULL CHECK (length(trim(nome)) > 0),
  UNIQUE (id, evento_id)
);
CREATE INDEX idx_portoes_evento ON portoes(evento_id);

CREATE TABLE ingressos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  codigo TEXT COLLATE "C" NOT NULL UNIQUE CHECK (length(trim(codigo)) > 0 AND codigo = trim(codigo)),
  evento_id BIGINT NOT NULL REFERENCES eventos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  portao_id BIGINT NOT NULL,
  utilizado INTEGER NOT NULL DEFAULT 0 CHECK (utilizado IN (0, 1)),
  FOREIGN KEY (portao_id, evento_id) REFERENCES portoes(id, evento_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX idx_ingressos_evento_portao ON ingressos(evento_id, portao_id);
CREATE INDEX idx_ingressos_portao_evento ON ingressos(portao_id, evento_id);

CREATE TABLE recebimentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  dispositivo TEXT COLLATE "C" NOT NULL CHECK (length(trim(dispositivo)) > 0 AND dispositivo = trim(dispositivo)),
  id_local TEXT COLLATE "C" NOT NULL CHECK (length(trim(id_local)) > 0 AND id_local = trim(id_local)),
  conteudo_normalizado TEXT NOT NULL CHECK (json_typeof(conteudo_normalizado::json) = 'object'),
  status TEXT NOT NULL CHECK (status IN ('CONFIRMADA', 'CONFLITO', 'REJEITADA')),
  motivo TEXT,
  recebido_em TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    CHECK (instante_utc_valido(recebido_em)),
  UNIQUE (dispositivo, id_local),
  CHECK ((status = 'CONFIRMADA' AND motivo IS NULL)
    OR (status IN ('CONFLITO', 'REJEITADA') AND motivo IS NOT NULL AND length(trim(motivo)) > 0))
);

CREATE TABLE validacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  ingresso_id BIGINT NOT NULL UNIQUE REFERENCES ingressos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  recebimento_id BIGINT NOT NULL UNIQUE REFERENCES recebimentos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  data_hora_cliente TEXT CHECK (data_hora_cliente IS NULL OR instante_utc_valido(data_hora_cliente)),
  data_hora_servidor TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    CHECK (instante_utc_valido(data_hora_servidor))
);
CREATE INDEX idx_validacoes_data_servidor ON validacoes(data_hora_servidor);
