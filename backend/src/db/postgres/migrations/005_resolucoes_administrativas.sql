CREATE TABLE resolucoes_administrativas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  recebimento_id BIGINT NOT NULL UNIQUE REFERENCES recebimentos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  administrador_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  status_administrativo TEXT NOT NULL DEFAULT 'RESOLVIDA' CHECK (status_administrativo = 'RESOLVIDA'),
  justificativa TEXT NOT NULL CHECK (length(justificativa) BETWEEN 10 AND 1000 AND justificativa = trim(justificativa)),
  data_hora_servidor TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    CHECK (instante_utc_valido(data_hora_servidor))
);
CREATE INDEX idx_resolucoes_administrador ON resolucoes_administrativas(administrador_id);
-- JSONB somente na expressão do índice; o conteúdo armazenado continua TEXT.
CREATE INDEX idx_recebimentos_evento_pendencia ON recebimentos
  ((conteudo_normalizado::jsonb -> 'eventoId'), id) WHERE status IN ('CONFLITO', 'REJEITADA');

CREATE FUNCTION resolucao_exigir_recibo_e_administrador() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM recebimentos WHERE id = NEW.recebimento_id AND status IN ('CONFLITO', 'REJEITADA'))
    OR NOT EXISTS (SELECT 1 FROM usuarios WHERE id = NEW.administrador_id AND papel = 'ADMINISTRADOR' AND ativo = 1) THEN
    RAISE EXCEPTION 'RESOLUCAO_NAO_PERMITIDA' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER resolucoes_exigir_recibo_e_administrador BEFORE INSERT ON resolucoes_administrativas
  FOR EACH ROW EXECUTE FUNCTION resolucao_exigir_recibo_e_administrador();
CREATE TRIGGER resolucoes_impedir_alteracao BEFORE UPDATE ON resolucoes_administrativas
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_historico('RESOLUCAO_IMUTAVEL');
CREATE TRIGGER resolucoes_impedir_exclusao BEFORE DELETE ON resolucoes_administrativas
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_historico('RESOLUCAO_IMUTAVEL');
CREATE TRIGGER resolucoes_impedir_truncate BEFORE TRUNCATE ON resolucoes_administrativas
  FOR EACH STATEMENT EXECUTE FUNCTION impedir_mutacao_historico('RESOLUCAO_IMUTAVEL');
