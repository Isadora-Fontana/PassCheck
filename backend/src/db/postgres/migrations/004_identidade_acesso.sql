CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  usuario TEXT COLLATE "C" NOT NULL UNIQUE CHECK (length(usuario) BETWEEN 3 AND 64 AND usuario = lower(trim(usuario))),
  senha_hash TEXT NOT NULL CHECK (length(senha_hash) > 0),
  papel TEXT NOT NULL CHECK (papel IN ('ADMINISTRADOR', 'OPERADOR')),
  ativo INTEGER NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
  versao_token BIGINT NOT NULL DEFAULT 0 CHECK (versao_token BETWEEN 0 AND 9007199254740991),
  criado_em TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE usuarios_eventos (
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  evento_id BIGINT NOT NULL REFERENCES eventos(id) ON DELETE RESTRICT,
  PRIMARY KEY (usuario_id, evento_id)
);
CREATE TABLE usuarios_portoes (
  usuario_id BIGINT NOT NULL,
  evento_id BIGINT NOT NULL,
  portao_id BIGINT NOT NULL,
  PRIMARY KEY (usuario_id, evento_id, portao_id),
  FOREIGN KEY (usuario_id, evento_id) REFERENCES usuarios_eventos(usuario_id, evento_id) ON DELETE CASCADE,
  FOREIGN KEY (portao_id, evento_id) REFERENCES portoes(id, evento_id) ON DELETE RESTRICT
);
CREATE TABLE instalacoes (
  dispositivo TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (length(dispositivo) BETWEEN 1 AND 128
    AND dispositivo !~ '[^A-Za-z0-9._:-]' AND left(dispositivo, 5) <> 'seed:'),
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  ativo INTEGER NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
  criado_em TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE INDEX idx_instalacoes_usuario ON instalacoes(usuario_id);
CREATE INDEX idx_usuarios_eventos_evento ON usuarios_eventos(evento_id);
CREATE INDEX idx_usuarios_portoes_portao ON usuarios_portoes(portao_id, evento_id);

CREATE FUNCTION usuario_revogar_tokens() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- BEFORE evita a atualização recursiva necessária no SQLite.
  IF NEW.usuario <> OLD.usuario OR NEW.senha_hash <> OLD.senha_hash
    OR NEW.papel <> OLD.papel OR NEW.ativo <> OLD.ativo THEN
    NEW.versao_token := NEW.versao_token + 1;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER usuarios_revogar_tokens BEFORE UPDATE OF usuario, senha_hash, papel, ativo ON usuarios
  FOR EACH ROW EXECUTE FUNCTION usuario_revogar_tokens();

CREATE FUNCTION instalacao_preservar_identidade() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.dispositivo <> OLD.dispositivo OR NEW.usuario_id <> OLD.usuario_id THEN
    RAISE EXCEPTION 'Identidade da instalacao imutavel' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER instalacoes_preservar_identidade BEFORE UPDATE OF dispositivo, usuario_id ON instalacoes
  FOR EACH ROW EXECUTE FUNCTION instalacao_preservar_identidade();
