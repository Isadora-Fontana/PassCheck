CREATE TABLE auditoria_divergencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
  recebimento_id BIGINT NOT NULL REFERENCES recebimentos(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  correlacao_id TEXT NOT NULL CHECK (length(correlacao_id) = 36),
  motivo TEXT NOT NULL CHECK (motivo = 'IDEMPOTENCIA_DIVERGENTE'),
  hash_original TEXT NOT NULL CHECK (hash_original ~ '^[0-9a-f]{64}$'),
  hash_apresentado TEXT NOT NULL CHECK (hash_apresentado ~ '^[0-9a-f]{64}$'),
  data_hora_servidor TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    CHECK (instante_utc_valido(data_hora_servidor))
);
CREATE INDEX idx_auditoria_recebimento ON auditoria_divergencias(recebimento_id);
CREATE INDEX idx_auditoria_correlacao ON auditoria_divergencias(correlacao_id);
CREATE TRIGGER auditoria_divergencias_impedir_alteracao BEFORE UPDATE ON auditoria_divergencias
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_historico('AUDITORIA_IMUTAVEL');
CREATE TRIGGER auditoria_divergencias_impedir_exclusao BEFORE DELETE ON auditoria_divergencias
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_historico('AUDITORIA_IMUTAVEL');
CREATE TRIGGER auditoria_divergencias_impedir_truncate BEFORE TRUNCATE ON auditoria_divergencias
  FOR EACH STATEMENT EXECUTE FUNCTION impedir_mutacao_historico('AUDITORIA_IMUTAVEL');
